// node --test desktop-tauri/bridge/font-face.test.ts
//
// What a Windows Terminal settings.json says about its font, and what may count as a
// font's name. Everything here is text in, text out: no file is read.
import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import { parseJsonc, pickFont, sanitiseFace, sanitiseFaces, sanitiseSize, stripJsonc } from './font-face.ts';

describe('JSON with comments and trailing commas', () => {
  test('line and block comments are dropped', () => {
    assert.deepEqual(parseJsonc('{ // the schema\n  "a": 1, /* two */ "b": 2 // end\n}'), { a: 1, b: 2 });
    assert.deepEqual(parseJsonc('/* first */ [1, /* between */ 2]'), [1, 2]);
    assert.deepEqual(parseJsonc('{"a":1}// no newline at the end'), { a: 1 });
  });

  test('CRLF ends a line comment', () => {
    assert.deepEqual(parseJsonc('{\r\n// c\r\n"a": 1\r\n}'), { a: 1 });
  });

  test('a trailing comma goes, from an object or an array, with blanks or a comment after it', () => {
    assert.deepEqual(parseJsonc('{"a": [1, 2,], "b": {"c": 3,},}'), { a: [1, 2], b: { c: 3 } });
    assert.deepEqual(parseJsonc('{"a": 1, // last one\n}'), { a: 1 });
    assert.deepEqual(parseJsonc('[1, 2, /* more later */ ]'), [1, 2]);
    assert.deepEqual(parseJsonc('{"a": [\n  1,\n  2,\n],\n}'), { a: [1, 2] });
  });

  test('a comma that is not trailing stays, and a missing value is still an error', () => {
    assert.deepEqual(parseJsonc('[1,2]'), [1, 2]);
    assert.equal(parseJsonc('[1,,2]'), undefined);
    assert.equal(parseJsonc('{"a": }'), undefined);
  });

  test('what looks like a comment inside a string is the string', () => {
    assert.deepEqual(parseJsonc('{"url": "https://example.test/a//b", "x": "/* not a comment */", "y": "a, ]"}'), { url: 'https://example.test/a//b', x: '/* not a comment */', y: 'a, ]' });
  });

  test('an escaped quote does not end a string early', () => {
    assert.deepEqual(parseJsonc('{"a": "say \\"hi\\" // still the string", "b": 1,}'), { a: 'say "hi" // still the string', b: 1 });
    assert.deepEqual(parseJsonc('{"a": "back\\\\", "b": 1 // after}\n}'), { a: 'back\\', b: 1 });
  });

  test('a byte order mark at the start is ignored', () => {
    assert.deepEqual(parseJsonc('﻿{"a": 1}'), { a: 1 });
  });

  test('a comment never glues two tokens together', () => {
    assert.equal(parseJsonc('[1/**/2]'), undefined);
    assert.equal(stripJsonc('a/**/b'), 'a b');
  });

  test('a block comment that is never closed runs to the end, and what is left is judged as JSON', () => {
    assert.deepEqual(parseJsonc('{"a": 1} /* unfinished'), { a: 1 });
    assert.equal(parseJsonc('{"a": 1, /* unfinished'), undefined);
  });

  test('text that is not JSON at all is undefined, never a throw', () => {
    for (const bad of ['', '   ', 'not json', '{', '}', '{"a": "unterminated', "{'a': 1}", '{"a": 1} {"b": 2}', 'undefined', '\0\0\0']) assert.equal(parseJsonc(bad), undefined, JSON.stringify(bad));
  });

  test('a real settings file, comments and all', () => {
    const text = `// This file was initially generated by Windows Terminal 1.21
{
    "$help": "https://aka.ms/terminal-documentation",
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "actions": [
        { "command": { "action": "copy", "singleLine": false }, "id": "User.copy.644BA8F2", }, // Ctrl+C
    ],
    "defaultProfile": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}",
    "profiles": {
        "defaults": { "font": { "face": "CaskaydiaCove Nerd Font Mono", }, },
        "list": [ { "guid": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}", "name": "Windows PowerShell", }, ],
    },
}
`;
    assert.deepEqual(pickFont(parseJsonc(text)), { face: 'CaskaydiaCove Nerd Font Mono' });
  });
});

describe('what may be a font face', () => {
  test('ordinary names are kept as written', () => {
    for (const name of ['Cascadia Code', 'CaskaydiaCove Nerd Font Mono', 'JetBrainsMono NF', 'MesloLGS NF', 'Fira Code', 'Cascadia Code (Variable)', 'IBM Plex Mono', 'Source_Code-Pro', 'Noto Sans Mono CJK JP', 'Consolas', 'Hack Nerd Font Mono 2.0', 'ＭＳ ゴシック', 'Lucida Console', 'M+ 1m', 'M+ 1code', 'Cascadia Code & Friends', 'Fira Code+Symbols']) {
      assert.equal(sanitiseFace(name), name, name);
    }
  });

  test('a + or & in a name is kept, and a list of such names is split only at its commas', () => {
    assert.deepEqual(sanitiseFaces('M+ 1m, Symbols Nerd Font Mono'), ['M+ 1m', 'Symbols Nerd Font Mono']);
    assert.deepEqual(pickFont({ profiles: { defaults: { font: { face: 'M+ 1m', size: 12 } } } }), { face: 'M+ 1m', size: 12 });
    // Only symbols is not a name: it needs a letter or a digit.
    for (const v of ['+', '&', '+&', ' + & ']) assert.equal(sanitiseFace(v), undefined, v);
  });

  test('blanks around a name and inside it are tidied', () => {
    assert.equal(sanitiseFace('  Fira   Code  '), 'Fira Code');
    assert.equal(sanitiseFace('Fira Code\t'), undefined, 'a tab is not a space');
  });

  test('Windows Terminal takes a list of fonts: the first usable name is kept', () => {
    assert.equal(sanitiseFace('CaskaydiaCove NF, Segoe UI Emoji'), 'CaskaydiaCove NF');
    assert.equal(sanitiseFace(' , Fira Code'), 'Fira Code');
  });

  test('the whole list is kept for the stack: every usable name, in order, once, at most six', () => {
    assert.deepEqual(sanitiseFaces('Cascadia Code, Symbols Nerd Font Mono'), ['Cascadia Code', 'Symbols Nerd Font Mono']);
    assert.deepEqual(sanitiseFaces('Fira Code,a"; },  fira   code ,Hack NF'), ['Fira Code', 'Hack NF'], 'an unusable one and a repeat (in any case) go');
    assert.deepEqual(sanitiseFaces(['Fira Code', 'Cascadia Code, Hack NF', 7, null, {}]), ['Fira Code', 'Cascadia Code', 'Hack NF'], 'an array of texts, each a list; other things are skipped');
    assert.deepEqual(sanitiseFaces('a, b, c, d, e, f, g, h'), ['a', 'b', 'c', 'd', 'e', 'f']);
    for (const v of ['', ',', undefined, null, 5, {}, [], [5], 'x"; }', 'a'.repeat(1_000_000)]) assert.deepEqual(sanitiseFaces(v), [], String(v).slice(0, 20));
    assert.deepEqual(sanitiseFaces([['Fira Code']]), [], 'no digging into nested arrays');
  });

  test('a hostile name is refused, whatever it tries', () => {
    const hostile = [
      "x'; } body { background: url(http://evil.test/p) } a { font-family: 'y",
      'x"; } body { display: none } a { font-family: "y',
      'Fira Code\\',
      'Fira Code\\27 ',
      'Fira\nCode',
      'Fira\rCode',
      'Fira\tCode\u0000',
      'a;b',
      'a{b}',
      '<script>alert(1)</script>',
      '</style><img src=x onerror=1>',
      'a/*b*/c',
      'a//b',
      'url(javascript:1)',
      '@import "x"',
      'Fira Code!important',
      'Fira Code‮',
      'Fira​Code',
      'a:b',
      'a=b',
      '`x`',
      '$(x)',
      '%PATH%',
      'a|b',
      // The + and & are allowed, but not as a way to something else.
      'a+b;c',
      "M+ 1m'; } a { color: red",
      'M+ 1m"; } a { color: red',
      'a&b;',
      'a&#59; b',
      'a&b\nc',
      'a+b/*c*/',
      'a+b\\',
    ];
    for (const name of hostile) assert.equal(sanitiseFace(name), undefined, JSON.stringify(name));
  });

  test('a hostile name in a list does not spoil a good one beside it, and is never kept', () => {
    assert.equal(sanitiseFace('x"; } a { color: red, Fira Code'), 'Fira Code');
    assert.equal(sanitiseFace('x"; } a { color: red'), undefined);
  });

  test('empty, punctuation only, or not text is nothing', () => {
    for (const v of ['', ' ', '...', '---', '( )', '_', ',', ',,', undefined, null, 5, true, {}, [], ['Fira Code'], { toString: () => 'Fira' }]) assert.equal(sanitiseFace(v), undefined, String(v));
  });

  test('100 characters is the most', () => {
    assert.equal(sanitiseFace('a'.repeat(100)), 'a'.repeat(100));
    assert.equal(sanitiseFace('a'.repeat(101)), undefined);
    assert.equal(sanitiseFace(`${'a '.repeat(60)}b`), undefined);
    assert.equal(sanitiseFace('a'.repeat(1_000_000)), undefined);
  });

  test('sizes are points between 4 and 96, and anything else is nothing', () => {
    assert.equal(sanitiseSize(12), 12);
    assert.equal(sanitiseSize(10.5), 10.5);
    assert.equal(sanitiseSize(10.26), 10.3);
    for (const v of [0, -1, 3.9, 97, NaN, Infinity, '12', null, undefined, {}, [12]]) assert.equal(sanitiseSize(v), undefined, String(v));
  });
});

describe('the default profile', () => {
  const GUID = '{61c54bbd-c2c6-5271-96e7-009a87ff44bf}';
  const OTHER = '{574e775e-4f2a-5b96-ac1e-a2962a402336}';

  test("the default profile's own font wins over the defaults", () => {
    const settings = {
      defaultProfile: GUID,
      profiles: {
        defaults: { font: { face: 'Defaults Font', size: 9 } },
        list: [
          { guid: OTHER, font: { face: 'Other Font', size: 20 } },
          { guid: GUID, font: { face: 'Mine NF', size: 11 } },
        ],
      },
    };
    assert.deepEqual(pickFont(settings), { face: 'Mine NF', size: 11 });
  });

  test('a list of faces is kept whole, in order: the second font is where a prompt\'s symbols come from', () => {
    const face = 'Cascadia Code, Symbols Nerd Font Mono';
    assert.deepEqual(pickFont({ defaultProfile: GUID, profiles: { list: [{ guid: GUID, font: { face, size: 12 } }] } }), { face: 'Cascadia Code', faces: ['Cascadia Code', 'Symbols Nerd Font Mono'], size: 12 });
    assert.deepEqual(pickFont({ profiles: { defaults: { font: { face } } } }), { face: 'Cascadia Code', faces: ['Cascadia Code', 'Symbols Nerd Font Mono'] });
    assert.deepEqual(pickFont({ profiles: { defaults: { fontFace: face } } }), { face: 'Cascadia Code', faces: ['Cascadia Code', 'Symbols Nerd Font Mono'] }, 'the older spelling too');
    // One name is as before: no list beside it.
    assert.deepEqual(pickFont({ profiles: { defaults: { font: { face: 'Cascadia Code' } } } }), { face: 'Cascadia Code' });
    // A profile's list replaces the defaults' list, not adds to it.
    assert.deepEqual(pickFont({ defaultProfile: GUID, profiles: { defaults: { font: { face: 'A, B' } }, list: [{ guid: GUID, font: { face: 'C' } }] } }), { face: 'C' });
    // Unusable names in a list are left out of it.
    assert.deepEqual(pickFont({ profiles: { defaults: { font: { face: 'Cascadia Code, x"; }, Symbols Nerd Font Mono' } } } }), { face: 'Cascadia Code', faces: ['Cascadia Code', 'Symbols Nerd Font Mono'] });
  });

  test('the guid matches whatever its case, and with or without the braces Windows Terminal writes', () => {
    const list = [{ guid: GUID, font: { face: 'Mine NF' } }];
    assert.equal(pickFont({ defaultProfile: GUID.toUpperCase(), profiles: { list } }).face, 'Mine NF');
    assert.equal(pickFont({ defaultProfile: `  ${GUID} `, profiles: { list } }).face, 'Mine NF');
  });

  test("a profile that says nothing about the font gets the defaults'", () => {
    const settings = { defaultProfile: GUID, profiles: { defaults: { font: { face: 'Defaults NF', size: 10.5 } }, list: [{ guid: GUID, name: 'PowerShell' }] } };
    assert.deepEqual(pickFont(settings), { face: 'Defaults NF', size: 10.5 });
  });

  test('face and size are each taken from the nearest place that has one', () => {
    const settings = { defaultProfile: GUID, profiles: { defaults: { font: { face: 'Defaults NF', size: 10 } }, list: [{ guid: GUID, font: { size: 14 } }] } };
    assert.deepEqual(pickFont(settings), { face: 'Defaults NF', size: 14 });
  });

  test('another profile in the list does not count, whatever its font', () => {
    const settings = { defaultProfile: GUID, profiles: { list: [{ guid: OTHER, font: { face: 'Other Font' } }, { guid: GUID }] } };
    assert.deepEqual(pickFont(settings), {});
  });

  test('a default profile that is not in the list, or none named, leaves the defaults', () => {
    const defaults = { font: { face: 'Defaults NF' } };
    assert.equal(pickFont({ defaultProfile: '{00000000-0000-0000-0000-000000000000}', profiles: { defaults, list: [{ guid: OTHER, font: { face: 'Other Font' } }] } }).face, 'Defaults NF');
    assert.equal(pickFont({ profiles: { defaults, list: [{ guid: OTHER, font: { face: 'Other Font' } }] } }).face, 'Defaults NF');
    assert.equal(pickFont({ defaultProfile: 7, profiles: { defaults } }).face, 'Defaults NF');
  });

  test('older files name the default profile and use fontFace and fontSize', () => {
    assert.deepEqual(pickFont({ defaultProfile: GUID, profiles: { defaults: { fontFace: 'Old Defaults', fontSize: 10 }, list: [{ guid: GUID, fontFace: 'Old Mine', fontSize: 12 }] } }), { face: 'Old Mine', size: 12 });
    assert.deepEqual(pickFont({ profiles: { defaults: { fontFace: 'Old Defaults', fontSize: 10 } } }), { face: 'Old Defaults', size: 10 });
  });

  test('font.face beats fontFace in the same place, and a profile beats the defaults across the two spellings', () => {
    assert.equal(pickFont({ profiles: { defaults: { font: { face: 'New' }, fontFace: 'Old' } } }).face, 'New');
    assert.equal(pickFont({ defaultProfile: GUID, profiles: { defaults: { font: { face: 'New defaults' } }, list: [{ guid: GUID, fontFace: 'Old mine' }] } }).face, 'Old mine');
  });

  test('the oldest files, where profiles is the list itself, are read too', () => {
    assert.deepEqual(pickFont({ defaultProfile: GUID, profiles: [{ guid: OTHER, fontFace: 'Other' }, { guid: GUID, fontFace: 'Consolas', fontSize: 11 }] }), { face: 'Consolas', size: 11 });
  });

  test('the default profile can be named by its name', () => {
    assert.equal(pickFont({ defaultProfile: 'Windows PowerShell', profiles: { list: [{ name: 'windows powershell', font: { face: 'By Name' } }] } }).face, 'By Name');
  });

  test('no font anywhere is nothing', () => {
    assert.deepEqual(pickFont({ defaultProfile: GUID, profiles: { defaults: {}, list: [{ guid: GUID }] } }), {});
    assert.deepEqual(pickFont({}), {});
  });

  test('a face that fails the check is not used, and the next place is tried', () => {
    const settings = { defaultProfile: GUID, profiles: { defaults: { font: { face: 'Defaults NF' } }, list: [{ guid: GUID, font: { face: 'x"; } a { color: red' } }] } };
    assert.deepEqual(pickFont(settings), { face: 'Defaults NF' });
    assert.deepEqual(pickFont({ profiles: { defaults: { font: { face: 'x"; } a { color: red', size: 12 } } } }), { size: 12 });
  });

  test('wrong shapes are nothing, never a throw', () => {
    const odd: unknown[] = [null, undefined, 5, 'text', true, [], [1, 2], { profiles: 'x' }, { profiles: null }, { profiles: { list: 'x' } }, { profiles: { list: [null, 5, 'x', [], {}] } }, { profiles: { defaults: 'x' } }, { profiles: { defaults: { font: 'Fira' } } }, { profiles: { defaults: { font: { face: 7, size: '12' } } } }, { defaultProfile: {}, profiles: {} }];
    for (const s of odd) assert.deepEqual(pickFont(s), {}, JSON.stringify(s));
  });

  test("keys named like Object's own do not reach the answer", () => {
    const hostile = parseJsonc('{"__proto__": {"font": {"face": "Evil"}}, "profiles": {"__proto__": {"defaults": {"font": {"face": "Evil"}}}, "constructor": {"font": {"face": "Evil"}}}}');
    assert.deepEqual(pickFont(hostile), {});
    assert.equal(({} as { font?: unknown }).font, undefined, 'Object.prototype was not changed');
  });
});
